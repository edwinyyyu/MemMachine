"""Sampled queries from every dataset, with their documents and gold, for review (EXAMPLES.md).

For each example: the query as sent, the document, each gold span in context (marked
⟦like this⟧), and how EventMemory's segments divide the gold: how many segments a span
overlaps (all of them must be read for the span to count as read) and how much non-gold text
comes with it. Examples are the first queries in the fixed sample order, so they are
reproducible and not hand-picked.
"""

from __future__ import annotations

import textwrap

from rbench import partitions as pt
from rbench.datasets import DATASETS, info
from rbench.metrics import trim
from rbench.paths import ROOT
from rbench.samples import sample_order
from rbench.schema import corpus, queries
from rbench.text import count

CONTEXT_CHARS = 350
MAX_QUERY_CHARS = 1500
MAX_SPAN_CHARS = 600


def _clip(text: str, n: int) -> str:
    return text if len(text) <= n else text[: n // 2] + f" […{len(text) - n:,} characters…] " + text[-n // 2 :]


def _quote(text: str) -> str:
    return "\n".join("> " + line if line.strip() else ">" for line in text.splitlines()) or "> (empty)"


def example(dataset: str, qi: int, chunkings: tuple[str, ...]) -> list[str]:
    q = queries(dataset)[qi]
    ds = info(dataset)
    docs = corpus(dataset)
    query = q["variants"][ds.default_variant]
    out = [f"### {dataset} · {q['qid']}\n", f"**Query** ({count([query])[0]} tokens, variant `{ds.default_variant}`):\n",
           _quote(_clip(query, MAX_QUERY_CHARS)), ""]
    alternative = q["gold"][0]
    n_alt = len(q["gold"])
    out.append(f"**Gold:** {len(alternative)} span(s) in the first of {n_alt} acceptable answer(s).\n")
    for k, (doc_id, s, e) in enumerate(alternative[:4]):
        d = docs.index[doc_id]
        text = docs.texts[d]
        s, e = trim(text, s, e)
        span_tokens = count([text[s:e]])[0]
        out.append(f"Span {k + 1}: document `{doc_id}` ({docs.titles[d] or 'untitled'}, {count([text])[0]:,} tokens), "
                   f"{span_tokens} tokens, {100 * s / max(1, len(text)):.0f}% into the document.\n")
        before = text[max(0, s - CONTEXT_CHARS) : s]
        after = text[e : e + CONTEXT_CHARS]
        out.append(_quote(("…" if s > CONTEXT_CHARS else "") + before + "⟦" + _clip(text[s:e], MAX_SPAN_CHARS) + "⟧" + after
                          + ("…" if e + CONTEXT_CHARS < len(text) else "")))
        cells = []
        p = pt.part(dataset, q)
        for c in chunkings:
            seg = pt.offline(dataset, p.key, c)[0]
            hit = [i for i, _ in pt.gold([[(p.number[doc_id], s, e)]], p, seg).alternatives[0][0]]
            read = int(seg.tokens[hit].sum())
            cells.append(f"{c}: {len(hit)} segment(s), {read} tokens to read it ({span_tokens / max(1, read):.0%} gold)")
        if cells:
            out.append("\nEventMemory segments that must be read for this span: " + "; ".join(cells) + ".\n")
        out.append("")
    if len(alternative) > 4:
        out.append(f"(+{len(alternative) - 4} more spans)\n")
    return out


def history_example(dataset: str, qi: int, size: int = 500) -> list[str]:
    """A history question: the question, its type and date, and each gold turn with the turns
    around it, dated as EventMemory stamps them, plus how many segments the gold turn spans."""
    from rbench.datasets.longmemeval import history

    q = queries(dataset)[qi]
    h = history(dataset, q["qid"])
    p = pt.part(dataset, q)
    seg = pt.offline(dataset, p.key, f"seg{size}")[0]
    out = [f"### {dataset} · {q['qid']} · {q['features']['question_type']}\n",
           f"**Question** (asked {q['features']['question_date']}):\n", _quote(q["variants"]["question"]), "",
           f"**Gold:** {len(q['gold_turns'][0])} turn(s) in {len(q['gold_sessions'])} evidence session(s) of "
           f"{len(h['sessions'])}.\n"]
    for s_, t in q["gold_turns"][0][:4]:
        session = h["sessions"][s_]
        out.append(f"Session {s_ + 1} ({session['date']}), turns {max(0, t - 1) + 1}–{min(len(session['turns']), t + 2)}:\n")
        lines = []
        for i in range(max(0, t - 1), min(len(session["turns"]), t + 2)):
            turn = session["turns"][i]
            text = _clip(turn["content"], MAX_SPAN_CHARS)
            lines.append(f"{turn['role']}: " + (f"⟦{text}⟧" if i == t else text))
        out.append(_quote("\n".join(lines)))
        n = int((seg.event == p.number[f"session {s_}, turn {t}"]).sum())
        out.append(f"\nThe gold turn is {count([session['turns'][t]['content']])[0]} tokens, {n} segment(s) at {size} "
                   f"characters.\n")
    return out


def write(n: int = 3, chunkings: tuple[str, ...] = ("seg500", "cut500")) -> str:
    out = ["# Examples\n",
           "Generated by `python -m rbench examples`: the first queries of each dataset in the fixed sample order "
           "(not hand-picked). Gold is marked ⟦like this⟧ inside its surrounding text, with how many chunks or "
           "segments a reader must read to have all of it.\n"]
    for name, ds in DATASETS.items():
        if not ds.evaluated:
            continue
        out += [f"## {name}\n", textwrap.fill(f"Documents: {ds.documents}. Queries: {ds.queries}. Gold: {ds.gold}. "
                                              f"Scope: {ds.scope}.", 120), ""]
        picked = sample_order(name)[:n]  # the samples' own order: not hand-picked
        for qi in picked:
            out += history_example(name, qi) if ds.partitioned else example(name, qi, chunkings)
    path = ROOT / "EXAMPLES.md"
    path.write_text("\n".join(out) + "\n")
    return str(path)
